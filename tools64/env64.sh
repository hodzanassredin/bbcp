# Общие пути tools64. Подключение из скриптов tools64:
#   . "$(dirname "$0")/env64.sh"
# BB  — корень репо bbcp (вычисляется по расположению скрипта: клонировать
#       можно куда угодно, $HOME/sources не требуется).
# USE — 64-битный мир; по умолчанию ../bbcp64use рядом с репо,
#       переопределяется переменной окружения BBCP64USE.
BB="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
USE="${BBCP64USE:-$(dirname "$BB")/bbcp64use}"
